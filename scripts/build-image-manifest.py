"""Run from any directory after adding/removing/renaming study images."""
from pathlib import Path
import json
root = Path(__file__).resolve().parents[1]
files = sorted(p.name for p in (root / 'all_images').iterdir()
               if p.suffix.lower() in ('.png', '.jpg', '.jpeg') and p.name.startswith(('M', 'F')))
# Keep the server-side filename allowlist synchronized with the browser manifest.
# Counts and block offsets must still be reviewed if images are added or removed.
import re
rules_path = root / 'database.rules.json'
rules = json.loads(rules_path.read_text())
session = rules['rules']['responses']['$uid']['$session']
expected_count = int(re.search(r'== (\d+)', session['trial_count']['.validate']).group(1))
if len(files) != expected_count:
    raise SystemExit('Image count changed: review Firebase trial counts, slots, and block offsets before publishing.')
trial = session['trials']['$trial']
limits = trial['within_block_index']['.validate']
for prefix, label in [('M', 'Male'), ('F', 'Female')]:
    expected = int(re.search(label + r"' && newData.val\(\) <= (\d+)", limits).group(1))
    if sum(f.startswith(prefix) for f in files) != expected:
        raise SystemExit(f'{label} image count changed: review Firebase block offsets before publishing.')
if any(not re.fullmatch(r'[MF]_[A-Za-z0-9_+]+\.(jpeg|jpg|png)', f) for f in files):
    raise SystemExit('Unsupported image filename: review filenames before publishing.')
(root / 'image-manifest.js').write_text(
    '// Generated by scripts/build-image-manifest.py. Preserve exact filenames.\n'
    + 'window.IMAGE_FILES = ' + json.dumps(files, indent=2) + ';\n')
print(f'{len(files)} images: {sum(f.startswith("M") for f in files)} male, '
      f'{sum(f.startswith("F") for f in files)} female')

trial['filename']['.validate'] = (
    "newData.isString() && ((newData.parent().child('block').val() == 'Male' && newData.val().matches(/^M_.*$/)) || "
    "(newData.parent().child('block').val() == 'Female' && newData.val().matches(/^F_.*$/))) && "
    'newData.val().matches(/^(' + '|'.join(re.escape(f) for f in files) + ')$/)'
)
rules_path.write_text(json.dumps(rules, indent=2) + '\n')
print('Firebase filename allowlist updated. Republish database.rules.json when deploying.')
